import 'dart:convert';
import 'dart:math';
import 'package:flutter/material.dart';
import '../services/storage_service.dart';

class DiagnosticoAuthWidget extends StatelessWidget {
  final _storageService = StorageService();

  @override
  Widget build(BuildContext context) {
    return ElevatedButton.icon(
      onPressed: () async {
        await _ejecutarDiagnostico();
      },
      icon: Icon(Icons.bug_report),
      label: Text('?? Diagnóstico de Auth'),
      style: ElevatedButton.styleFrom(
        backgroundColor: Colors.orange,
        padding: EdgeInsets.symmetric(horizontal: 20, vertical: 12),
      ),
    );
  }

  Future<void> _ejecutarDiagnostico() async {
    print('');
    print('???????????????????????????????????????????????????????????');
    print('?? DIAGNÓSTICO DE AUTENTICACIÓN');
    print('???????????????????????????????????????????????????????????');
    print('');

    // ???????????????????????????????????????????????????????????
    // 1. VERIFICAR TOKEN EN STORAGE
    // ???????????????????????????????????????????????????????????
    print('1?? VERIFICANDO TOKEN EN STORAGE');
    print('???????????????????????????????????????????????????????????');
    
    final token = await _storageService.getAccessToken();
    
    if (token == null) {
      print('? Token es NULL');
      print('');
      print('?? PROBLEMA IDENTIFICADO:');
      print('   No hay token guardado en el storage.');
      print('');
      print('?? SOLUCIÓN:');
      print('   1. Cierra sesión si existe');
      print('   2. Haz login con Google nuevamente');
      print('   3. Verifica que veas el log "? Token guardado"');
      print('');
      print('?? Sin token, TODAS las peticiones autenticadas fallarán con 401');
      print('???????????????????????????????????????????????????????????');
      return;
    }

    print('? Token ENCONTRADO');
    print('   Longitud: ${token.length} caracteres');
    print('   Primeros 50 chars: ${token.substring(0, min(50, token.length))}...');
    print('   Últimos 30 chars: ...${token.substring(max(0, token.length - 30))}');
    print('');

    // ???????????????????????????????????????????????????????????
    // 2. VALIDAR FORMATO JWT
    // ???????????????????????????????????????????????????????????
    print('2?? VALIDANDO FORMATO JWT');
    print('???????????????????????????????????????????????????????????');
    
    final partes = token.split('.');
    print('   Número de partes: ${partes.length} (debe ser 3)');
    
    if (partes.length != 3) {
      print('? NO es un JWT válido');
      print('');
      print('?? PROBLEMA IDENTIFICADO:');
      print('   El token guardado no tiene formato JWT válido.');
      print('   Un JWT debe tener 3 partes separadas por puntos: header.payload.signature');
      print('');
      print('?? ANÁLISIS:');
      print('   ¿Puede ser un Firebase ID Token en lugar del token del backend?');
      print('');
      print('?? SOLUCIÓN:');
      print('   Verifica que en auth_service.dart, el método _saveSession()');
      print('   guarde response.data.accessToken, NO el Firebase token.');
      print('???????????????????????????????????????????????????????????');
      return;
    }
    
    print('? Formato JWT válido (3 partes)');
    print('');

    // ???????????????????????????????????????????????????????????
    // 3. DECODIFICAR PAYLOAD DEL JWT
    // ???????????????????????????????????????????????????????????
    print('3?? DECODIFICANDO PAYLOAD');
    print('???????????????????????????????????????????????????????????');
    
    try {
      final payload = partes[1];
      
      // Normalizar base64 (agregar padding si es necesario)
      String normalized = payload;
      while (normalized.length % 4 != 0) {
        normalized += '=';
      }
      
      final decoded = utf8.decode(base64Url.decode(normalized));
      final json = jsonDecode(decoded) as Map<String, dynamic>;
      
      print('? Payload decodificado exitosamente');
      print('');
      print('?? CLAIMS DEL TOKEN:');
      json.forEach((key, value) {
        // Acortar valores muy largos
        final valueStr = value.toString();
        final displayValue = valueStr.length > 50 
          ? '${valueStr.substring(0, 50)}...' 
          : valueStr;
        print('   • $key: $displayValue');
      });
      print('');
      
      // ???????????????????????????????????????????????????????????
      // 4. VERIFICAR CLAIMS IMPORTANTES
      // ???????????????????????????????????????????????????????????
      print('4?? VERIFICANDO CLAIMS IMPORTANTES');
      print('???????????????????????????????????????????????????????????');
      
      // Verificar nameid (user ID)
      final nameid = json['nameid'] ?? 
                    json['http://schemas.xmlsoap.org/ws/2005/05/identity/claims/nameidentifier'];
      if (nameid != null) {
        print('? nameid (User ID): $nameid');
      } else {
        print('? nameid NO encontrado');
        print('   Este claim es necesario para GetCurrentUserId()');
      }
      
      // Verificar email
      final email = json['email'] ?? 
                   json['http://schemas.xmlsoap.org/ws/2005/05/identity/claims/emailaddress'];
      if (email != null) {
        print('? email: $email');
      } else {
        print('?? email NO encontrado (opcional)');
      }
      
      // Verificar rol
      final role = json['role'] ?? 
                  json['http://schemas.microsoft.com/ws/2008/06/identity/claims/role'];
      if (role != null) {
        print('? role: $role');
      } else {
        print('?? role NO encontrado (puede causar problemas con políticas)');
      }
      
      print('');
      
      // ???????????????????????????????????????????????????????????
      // 5. VERIFICAR EXPIRACIÓN
      // ???????????????????????????????????????????????????????????
      print('5?? VERIFICANDO EXPIRACIÓN');
      print('???????????????????????????????????????????????????????????');
      
      final exp = json['exp'];
      if (exp == null) {
        print('?? Claim "exp" no encontrado');
        print('   No se puede verificar expiración');
      } else {
        final expInt = exp is int ? exp : int.tryParse(exp.toString());
        if (expInt == null) {
          print('? Claim "exp" inválido: $exp');
        } else {
          final expDate = DateTime.fromMillisecondsSinceEpoch(expInt * 1000);
          final now = DateTime.now();
          
          print('   Emitido: ${_formatDate(now)}');
          print('   Expira:  ${_formatDate(expDate)}');
          
          if (expDate.isAfter(now)) {
            final remaining = expDate.difference(now);
            print('');
            print('? TOKEN VÁLIDO - NO EXPIRADO');
            print('   Tiempo restante: ${_formatDuration(remaining)}');
          } else {
            final elapsed = now.difference(expDate);
            print('');
            print('? TOKEN EXPIRADO');
            print('   Expiró hace: ${_formatDuration(elapsed)}');
            print('');
            print('?? PROBLEMA IDENTIFICADO:');
            print('   El token ya no es válido porque expiró.');
            print('');
            print('?? SOLUCIÓN:');
            print('   Haz login nuevamente para obtener un token nuevo.');
          }
        }
      }
      
    } catch (e, stackTrace) {
      print('? Error al decodificar payload');
      print('   Error: $e');
      print('   StackTrace: $stackTrace');
    }
    
    print('');
    
    // ???????????????????????????????????????????????????????????
    // 6. VERIFICAR USUARIO EN STORAGE
    // ???????????????????????????????????????????????????????????
    print('6?? VERIFICANDO USUARIO EN STORAGE');
    print('???????????????????????????????????????????????????????????');
    
    final usuario = await _storageService.getUsuario();
    if (usuario == null) {
      print('?? Usuario NO encontrado en storage');
    } else {
      print('? Usuario encontrado');
      print('   ID: ${usuario.id}');
      print('   Email: ${usuario.email}');
      print('   Nombre: ${usuario.nombre ?? "N/A"}');
    }
    
    print('');
    
    // ???????????????????????????????????????????????????????????
    // 7. VERIFICAR SESIÓN ACTIVA
    // ???????????????????????????????????????????????????????????
    print('7?? VERIFICANDO SESIÓN ACTIVA');
    print('???????????????????????????????????????????????????????????');
    
    final hasSession = await _storageService.hasActiveSession();
    print('   hasActiveSession(): $hasSession');
    
    if (hasSession) {
      print('? Hay sesión activa');
    } else {
      print('? NO hay sesión activa');
    }
    
    print('');
    print('???????????????????????????????????????????????????????????');
    print('? DIAGNÓSTICO COMPLETADO');
    print('???????????????????????????????????????????????????????????');
    print('');
    
    // ???????????????????????????????????????????????????????????
    // RESUMEN
    // ???????????????????????????????????????????????????????????
    print('?? RESUMEN:');
    print('???????????????????????????????????????????????????????????');
    
    if (token != null && partes.length == 3 && hasSession) {
      print('? Todo parece estar bien');
      print('');
      print('Si aún recibes 401, el problema puede estar en:');
      print('   1. El api_service.dart no está agregando el header Authorization');
      print('   2. El endpoint requiere permisos especiales (roles)');
      print('   3. El token expiró entre el diagnóstico y la petición');
      print('');
      print('?? SIGUIENTE PASO:');
      print('   Agrega los logs de debugging al api_service.dart');
      print('   para ver exactamente qué headers se están enviando.');
    } else {
      print('? Se encontraron problemas');
      print('   Revisa los detalles arriba.');
    }
    
    print('???????????????????????????????????????????????????????????');
    print('');
  }

  String _formatDate(DateTime date) {
    return '${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')} '
           '${date.hour.toString().padLeft(2, '0')}:${date.minute.toString().padLeft(2, '0')}:${date.second.toString().padLeft(2, '0')}';
  }

  String _formatDuration(Duration duration) {
    if (duration.inDays > 0) {
      return '${duration.inDays} días, ${duration.inHours % 24} horas';
    } else if (duration.inHours > 0) {
      return '${duration.inHours} horas, ${duration.inMinutes % 60} minutos';
    } else if (duration.inMinutes > 0) {
      return '${duration.inMinutes} minutos';
    } else {
      return '${duration.inSeconds} segundos';
    }
  }
}
